def representative_long(
    long_df: pd.DataFrame,
    assignments: pd.DataFrame,
) -> pd.DataFrame:
    assigned = assignments[
        assignments["assigned"]
    ][
        [
            "library",
            "pathway",
            "module",
        ]
    ].drop_duplicates()

    out = long_df.merge(
        assigned,
        on=[
            "library",
            "pathway",
        ],
        how="inner",
    )

    return out


def make_module_phenotype_profiles(
    rep_long: pd.DataFrame,
) -> pd.DataFrame:
    rows = []

    for (module, phenotype), sub in rep_long.groupby(
        ["module", "phenotype"]
    ):
        n_reps = sub[
            ["library", "pathway"]
        ].drop_duplicates().shape[0]

        n_sig = sub[
            sub["significant"]
        ][
            ["library", "pathway"]
        ].drop_duplicates().shape[0]

        median_nes = float(
            sub["NES"].median()
        )

        mean_nes = float(
            sub["NES"].mean()
        )

        rows.append(
            {
                "module": module,
                "phenotype": phenotype,
                "phenotype_label": PHENOTYPE_LABELS[phenotype],
                "axis": AXIS_MAP[phenotype],
                "n_representative_pathways": int(n_reps),
                "n_significant_representatives": int(n_sig),
                "significant_fraction": (
                    n_sig / n_reps
                    if n_reps > 0
                    else np.nan
                ),
                "median_NES": median_nes,
                "mean_NES": mean_nes,
                "median_abs_NES": float(
                    sub["NES"].abs().median()
                ),
            }
        )

    return pd.DataFrame(rows)


