def require(path: Path):
    if not path.exists():
        raise FileNotFoundError(f"Missing required input: {path}")


def normalize_pathway(text: str) -> str:
    text = str(text).replace("_", " ")
    text = re.sub(r"\s+", " ", text).strip()
    return text


def parse_leading_edge(value) -> set[str]:
    if pd.isna(value):
        return set()

    text = str(value).strip()

    if not text:
        return set()

    parts = re.split(r"[;,/|]+", text)

    if len(parts) == 1:
        parts = text.split()

    return {
        p.strip()
        for p in parts
        if p.strip()
        and p.strip().lower() not in {"nan", "none", "na"}
    }


def pathway_matches_rule(pathway: str, rule: dict) -> bool:
    text = normalize_pathway(pathway).lower()

    include_match = any(
        re.search(pattern, text, flags=re.IGNORECASE)
        for pattern in rule["include"]
    )

    if not include_match:
        return False

    exclude_match = any(
        re.search(pattern, text, flags=re.IGNORECASE)
        for pattern in rule["exclude"]
    )

    return not exclude_match


def assign_module(pathway: str) -> tuple[str | None, str | None]:
    for rule in MODULE_RULES:
        if pathway_matches_rule(pathway, rule):
            return rule["module"], "; ".join(rule["include"])

    return None, None


