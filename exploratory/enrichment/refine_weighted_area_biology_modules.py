"""
refine_weighted_area_biology_modules.py
=======================================

Turn the broad Weighted AREA pathway synthesis into a smaller, biologically
interpretable module-level analysis.

This script DOES NOT rerun GSEA. It consumes the outputs already generated by:

    exploratory/enrichment/analyze_weighted_area_biology.py

and collapses hundreds of overlapping pathways into a transparent set of
biological modules.

Main questions
--------------
1. What are the dominant biological modules?
2. Which modules form a shared core across cognition, amyloid, and tau?
3. Which modules are relatively enhanced for amyloid, tau, or cognition?
4. Which genes repeatedly drive each module without simply being global
   annotation hubs?
5. Which representative pathways support each module?

Method
------
Pathways are first reduced to the previously selected representative pathways
(from leading-edge Jaccard redundancy clustering). Representative pathways are
then assigned to biologically interpretable modules by explicit keyword rules.

The rules are intentionally transparent and are exported to CSV so that every
module assignment can be audited.

For each module and phenotype:
    module NES = median NES across assigned representative pathways

For each module and phenotype:
    significant fraction = fraction of assigned representative pathways with
                           GSEA FDR < 0.05

A module is called:
    Shared core
        if it has >= 1 significant representative pathway in all 3 axes and
        its mean NES has the same sign in all 3 axes.

    <axis>-enhanced
        if it is shared across all 3 axes, but one axis has an absolute mean
        NES at least ENHANCEMENT_DELTA larger than the mean of the other axes.

    <axis>-specific
        only under a stricter criterion: >= MIN_AXIS_SIG representative
        pathways significant on one axis, zero significant representatives on
        the other two axes, and weak mean signal on both other axes.

    Mixed / context-dependent
        otherwise.

Leading-edge genes
------------------
Global hub genes can dominate recurrence counts. Therefore module driver genes
are ranked by BOTH:
    - recurrence within the module
    - module specificity = module recurrence / recurrence across all modules

This makes the gene tables more useful than the earlier global UBC/proteasome
recurrence ranking.

Inputs
------
results/weighted_area_biology/
    pathway_long_all.csv
    representative_pathways.csv
    redundancy_clusters.csv

Outputs
-------
results/weighted_area_biology_refined/

Tables:
    module_assignment_audit.csv
    module_summary.csv
    module_phenotype_profiles.csv
    module_axis_profiles.csv
    module_driver_genes.csv
    module_representative_pathways.csv
    unassigned_representative_pathways.csv
    module_rules.csv

Figures:
    refined_module_phenotype_heatmap.png/.pdf
    refined_module_axis_profiles.png/.pdf
    refined_module_driver_genes.png/.pdf
"""

