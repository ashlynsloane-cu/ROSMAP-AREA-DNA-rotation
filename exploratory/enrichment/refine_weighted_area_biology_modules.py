def make_driver_genes(
    rep_long: pd.DataFrame,
) -> pd.DataFrame:

    rows = []

    sig = rep_long[
        rep_long["significant"]
    ].copy()

    for _, row in sig.iterrows():
        genes = parse_leading_edge(
            row["leading_edge_genes"]
        )

        for gene in genes:
            rows.append(
                {
                    "module": row["module"],
                    "gene": gene,
                    "library": row["library"],
                    "pathway": row["pathway"],
                    "phenotype": row["phenotype"],
                    "axis": row["axis"],
                    "NES": row["NES"],
                }
            )

    if not rows:
        return pd.DataFrame()

    exploded = pd.DataFrame(rows)

    module_counts = (
        exploded
        .groupby(
            [
                "module",
                "gene",
            ]
        )
        .agg(
            module_pathway_instances=("pathway", "size"),
            module_unique_pathways=("pathway", "nunique"),
            module_phenotypes=("phenotype", "nunique"),
            module_axes=("axis", "nunique"),
            mean_context_NES=("NES", "mean"),
        )
        .reset_index()
    )

    global_counts = (
        exploded
        .groupby("gene")
        .agg(
            global_pathway_instances=("pathway", "size"),
            global_unique_modules=("module", "nunique"),
        )
        .reset_index()
    )

    out = module_counts.merge(
        global_counts,
        on="gene",
        how="left",
    )

    out["module_specificity"] = (
        out["module_pathway_instances"]
        / out["global_pathway_instances"]
    )

    # Recurrence plus specificity. sqrt prevents huge recurrence counts from
    # completely dominating the ranking.
    out["driver_score"] = (
        np.sqrt(
            out["module_pathway_instances"]
        )
        * out["module_specificity"]
        * (
            1
            + 0.15 * (out["module_axes"] - 1)
        )
    )

    out["passes_driver_filter"] = (
        (
            out["module_pathway_instances"]
            >= MIN_DRIVER_RECURRENCE
        )
        & (
            out["module_specificity"]
            >= MIN_DRIVER_SPECIFICITY
        )
    )

    return out.sort_values(
        [
            "module",
            "passes_driver_filter",
            "driver_score",
            "module_unique_pathways",
        ],
        ascending=[
            True,
            False,
            False,
            False,
        ],
    )


