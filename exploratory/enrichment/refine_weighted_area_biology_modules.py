def make_module_representative_pathways(
    assignments: pd.DataFrame,
) -> pd.DataFrame:

    keep = assignments[
        assignments["assigned"]
    ].copy()

    columns = [
        "module",
        "library",
        "pathway",
        "direction",
        "cluster_size",
        "n_significant_phenotypes",
        "n_significant_axes",
        "significant_axes",
        "mean_NES_cognition",
        "mean_NES_amyloid",
        "mean_NES_tau",
        "mean_abs_NES",
    ]

    available = [
        c
        for c in columns
        if c in keep.columns
    ]

    return keep[
        available
    ].sort_values(
        [
            "module",
            "n_significant_phenotypes",
            "mean_abs_NES",
        ],
        ascending=[
            True,
            False,
            False,
        ],
    )


