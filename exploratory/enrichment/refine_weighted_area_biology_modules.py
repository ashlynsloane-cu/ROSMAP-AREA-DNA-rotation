def classify_module(
    module: str,
    axis_profiles: pd.DataFrame,
) -> dict:

    sub = axis_profiles[
        axis_profiles["module"] == module
    ].set_index("axis")

    if not all(
        axis in sub.index
        for axis in AXES
    ):
        return {
            "module_class": "Incomplete",
            "enhanced_axis": "",
            "enhancement_delta": np.nan,
        }

    mean_nes = {
        axis: float(
            sub.loc[
                axis,
                "mean_axis_NES",
            ]
        )
        for axis in AXES
    }

    abs_nes = {
        axis: abs(mean_nes[axis])
        for axis in AXES
    }

    sig_counts = {
        axis: int(
            sub.loc[
                axis,
                "n_axis_phenotypes_with_module_signal",
            ]
        )
        for axis in AXES
    }

    signs = {
        axis: np.sign(mean_nes[axis])
        for axis in AXES
        if mean_nes[axis] != 0
    }

    # Strict axis-specific first.
    for axis in AXES:
        others = [
            x
            for x in AXES
            if x != axis
        ]

        if (
            sig_counts[axis] >= MIN_AXIS_SIG
            and all(
                sig_counts[o] == 0
                for o in others
            )
            and all(
                abs_nes[o] < OTHER_AXIS_WEAK_ABS_NES
                for o in others
            )
        ):
            return {
                "module_class": f"{axis}-specific",
                "enhanced_axis": axis,
                "enhancement_delta": (
                    abs_nes[axis]
                    - np.mean(
                        [
                            abs_nes[o]
                            for o in others
                        ]
                    )
                ),
            }

    all_axes_signal = all(
        sig_counts[axis] >= 1
        for axis in AXES
    )

    same_direction = (
        len(set(signs.values())) == 1
        if len(signs) == 3
        else False
    )

    if all_axes_signal and same_direction:
        best_axis = max(
            AXES,
            key=lambda a: abs_nes[a],
        )

        other_axes = [
            a
            for a in AXES
            if a != best_axis
        ]

        delta = (
            abs_nes[best_axis]
            - np.mean(
                [
                    abs_nes[a]
                    for a in other_axes
                ]
            )
        )

        if delta >= ENHANCEMENT_DELTA:
            return {
                "module_class": f"{best_axis}-enhanced shared",
                "enhanced_axis": best_axis,
                "enhancement_delta": delta,
            }

        return {
            "module_class": "Shared core",
            "enhanced_axis": "",
            "enhancement_delta": delta,
        }

    return {
        "module_class": "Mixed / context-dependent",
        "enhanced_axis": "",
        "enhancement_delta": np.nan,
    }


def make_module_summary(
    assignments: pd.DataFrame,
    phenotype_profiles: pd.DataFrame,
    axis_profiles: pd.DataFrame,
) -> pd.DataFrame:

    rows = []

    assigned = assignments[
        assignments["assigned"]
    ]

    for module, sub in assigned.groupby("module"):

        libraries = sorted(
            sub["library"].unique().tolist()
        )

        rep_count = sub[
            ["library", "pathway"]
        ].drop_duplicates().shape[0]

        class_info = classify_module(
            module,
            axis_profiles,
        )

        axis_lookup = (
            axis_profiles[
                axis_profiles["module"] == module
            ]
            .set_index("axis")
        )

        row = {
            "module": module,
            "n_representative_pathways": int(rep_count),
            "n_libraries": int(len(libraries)),
            "libraries": ";".join(libraries),
            **class_info,
        }

        for axis in AXES:
            if axis in axis_lookup.index:
                row[f"{axis.lower()}_mean_NES"] = float(
                    axis_lookup.loc[
                        axis,
                        "mean_axis_NES",
                    ]
                )
                row[f"{axis.lower()}_mean_abs_NES"] = float(
                    axis_lookup.loc[
                        axis,
                        "mean_axis_abs_NES",
                    ]
                )
                row[f"{axis.lower()}_signal_phenotypes"] = int(
                    axis_lookup.loc[
                        axis,
                        "n_axis_phenotypes_with_module_signal",
                    ]
                )
            else:
                row[f"{axis.lower()}_mean_NES"] = np.nan
                row[f"{axis.lower()}_mean_abs_NES"] = np.nan
                row[f"{axis.lower()}_signal_phenotypes"] = 0

        row["overall_mean_abs_NES"] = float(
            phenotype_profiles[
                phenotype_profiles["module"] == module
            ]["median_NES"]
            .abs()
            .mean()
        )

        rows.append(row)

    return pd.DataFrame(rows).sort_values(
        [
            "n_representative_pathways",
            "overall_mean_abs_NES",
        ],
        ascending=[
            False,
            False,
        ],
    )


